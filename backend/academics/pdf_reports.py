"""Builds the downloadable PDF reports with ReportLab."""
from datetime import datetime
from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

BLUE = colors.HexColor("#2f5d9e")
LIGHT = colors.HexColor("#f3f6fb")
RED = colors.HexColor("#c0392b")
styles = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=styles["Title"], textColor=BLUE, fontSize=20, alignment=0, spaceAfter=2)
H2 = ParagraphStyle("h2", parent=styles["Heading2"], textColor=colors.HexColor("#1d3557"), spaceBefore=12)
SMALL = ParagraphStyle("small", parent=styles["Normal"], fontSize=9, textColor=colors.grey)
CELL = ParagraphStyle("cell", parent=styles["Normal"], fontSize=9, leading=11)


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.grey)
    canvas.drawString(15 * mm, 10 * mm, "GEU EduTrack - College Academic & Process Management System")
    canvas.drawRightString(195 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def _table(header, rows, widths, red_col=None):
    data = [header] + [[Paragraph(str(c), CELL) for c in r] for r in rows]
    t = Table(data, colWidths=widths, repeatRows=1)
    style = [("BACKGROUND", (0, 0), (-1, 0), BLUE), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
             ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, 0), 9),
             ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d9e1ee")),
             ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
             ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, LIGHT])]
    if red_col is not None:  # highlight low attendance
        for i, r in enumerate(rows, start=1):
            if "(LOW)" in str(r[red_col]):
                style.append(("TEXTCOLOR", (red_col, i), (red_col, i), RED))
    t.setStyle(TableStyle(style))
    return t


def _build(title, subtitle, user, parts):
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
                            topMargin=15 * mm, bottomMargin=18 * mm, title=title)
    who = user.get_full_name() or user.username
    story = [Paragraph(title, H1), Paragraph(subtitle, SMALL),
             Paragraph(f"Generated by {who} on {datetime.now():%d %b %Y, %I:%M %p}", SMALL),
             Spacer(1, 8)] + parts
    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()


def _pct(r):
    if r["percentage"] is None:
        return "-"
    return f'{r["percentage"]}%' + (" (LOW)" if r["low"] else "")


def attendance_pdf(rows, user):
    body = [Paragraph("Attendance below 75% is marked LOW.", SMALL), Spacer(1, 6)]
    if rows:
        body.append(_table(["Roll No", "Student", "Course", "Classes", "Present", "Attendance"],
                           [[r["roll_no"], r["student_name"], r["course_name"], r["total_classes"],
                             r["present"], _pct(r)] for r in rows],
                          [24 * mm, 36 * mm, 56 * mm, 18 * mm, 18 * mm, 28 * mm], red_col=5))
    else:
        body.append(Paragraph("No attendance records found.", styles["Normal"]))
    return _build("Attendance Report", "Attendance percentage per student and course", user, body)


def performance_pdf(rows, user):
    body = []
    if rows:
        body.append(_table(["Roll No", "Student", "Course", "Exams", "Average marks"],
                           [[r["roll_no"], r["student_name"], r["course_name"], r["exams"],
                             "-" if r["average"] is None else r["average"]] for r in rows],
                          [24 * mm, 40 * mm, 64 * mm, 20 * mm, 32 * mm]))
    else:
        body.append(Paragraph("No marks found.", styles["Normal"]))
    return _build("Academic Performance Report", "Average marks per student and course", user, body)


def student_pdf(student, att_rows, perf_rows, marks, user):
    info = Table([["Roll No", student.roll_no, "Branch", student.branch],
                  ["Name", student.name, "Year", student.year],
                  ["Email", student.email, "Phone", student.phone or "-"]],
                 colWidths=[22 * mm, 68 * mm, 22 * mm, 60 * mm])
    info.setStyle(TableStyle([("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                              ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
                              ("FONTSIZE", (0, 0), (-1, -1), 10),
                              ("BOX", (0, 0), (-1, -1), 0.5, BLUE), ("BACKGROUND", (0, 0), (-1, -1), LIGHT)]))
    parts = [info]
    parts.append(Paragraph("Attendance", H2))
    parts.append(_table(["Course", "Classes", "Present", "Attendance"],
                        [[r["course_name"], r["total_classes"], r["present"], _pct(r)] for r in att_rows],
                        [80 * mm, 25 * mm, 25 * mm, 40 * mm], red_col=3)
                 if att_rows else Paragraph("Not available.", styles["Normal"]))
    parts.append(Paragraph("Marks", H2))
    parts.append(_table(["Course", "Exam", "Date", "Marks"],
                        [[m.course.course_name, m.exam_type, m.exam_date, m.marks] for m in marks],
                        [80 * mm, 35 * mm, 30 * mm, 25 * mm])
                 if marks else Paragraph("No marks recorded.", styles["Normal"]))
    if perf_rows:
        parts.append(Paragraph("Overall performance", H2))
        parts.append(_table(["Course", "Exams", "Average"],
                            [[r["course_name"], r["exams"], "-" if r["average"] is None else r["average"]]
                             for r in perf_rows], [100 * mm, 35 * mm, 35 * mm]))
    return _build("Student Report", f"Complete academic report - {student.name}", user, parts)